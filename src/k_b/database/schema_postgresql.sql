-- K-B: physical data model (MPD) of the items database, for PostgreSQL 17 or later: IS JSON and
-- pg_input_is_valid come with 16, pg_database.datlocale, which kb create-db reads, with 17.
-- schema.sql, written for SQLite, is the reference: this script follows it table by table, column
-- by column, each CHECK translated; what differs, and why, is in docs/stockage.md
-- ("Ce qui est propre à SQLite"). A test writes on it the rows tests/test_schema.py writes on
-- schema.sql (tests/test_schema_postgresql.py).
-- The base is created out of K-B, in UTF8 and in the collation C (kb create-db checks it): text
-- sorts byte by byte, as in SQLite, and citext folds the case of ASCII letters alone, as
-- COLLATE NOCASE. Dates are UTC text, 'YYYY-MM-DDTHH:MM:SSZ', as in SQLite: both engines give the
-- same values, and the SQL compares them as text. A JSON list is text too, for the same reason.
-- No constraint is named here: PostgreSQL names the one of a primary key <table>_pkey, which
-- database/errors.py tells from the other unique constraints.

CREATE EXTENSION IF NOT EXISTS citext;

-- A date of the base: the form of strftime('%Y-%m-%dT%H:%M:%SZ'), and a day that exists, as the
-- CHECK of schema.sql, which compares the text with strftime of itself. pg_input_is_valid returns
-- false where a cast would raise an error, which would stop the import instead of refusing the
-- entry (database/errors.py).
CREATE DOMAIN utc_date AS text
    CHECK (VALUE ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]Z$'
        AND pg_input_is_valid(VALUE, 'timestamptz'));

-- A day of the base, written at midnight UTC.
CREATE DOMAIN utc_day AS text
    CHECK (VALUE ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T00:00:00Z$'
        AND pg_input_is_valid(VALUE, 'timestamptz'));

CREATE TABLE source (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code      text NOT NULL UNIQUE,
    label            text NOT NULL,
    source_type      text NOT NULL
        CHECK (source_type IN ('web_service', 'file', 'scraping', 'database', 'big_data')),
    acquisition_mode text NOT NULL CHECK (acquisition_mode IN ('watch', 'library', 'wiki'))
);

CREATE TABLE raw_data (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id     bigint NOT NULL REFERENCES source (id),
    raw_file_path text NOT NULL UNIQUE,
    stream        text NOT NULL,
    collected_at  utc_date NOT NULL
);

CREATE INDEX raw_data_source_id ON raw_data (source_id);

CREATE TABLE item (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        text NOT NULL
        CHECK (kind IN ('paper', 'vulnerability', 'newsletter_article', 'release', 'advisory',
            'zotero_entry', 'clip')),
    raw_data_id bigint NOT NULL REFERENCES raw_data (id),
    UNIQUE (id, kind)
);

CREATE INDEX item_raw_data_id ON item (raw_data_id);

-- A JSON list: a CASE, so that the cast to json runs only on a JSON array (IS JSON never raises).
CREATE TABLE publication (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arxiv_id     text NOT NULL UNIQUE CHECK (length(arxiv_id) <= 20),
    item_id      bigint UNIQUE REFERENCES item (id),
    title        text CHECK (length(title) <= 500),
    summary      text CHECK (length(summary) <= 5000),
    authors      text
        CHECK (CASE WHEN authors IS NOT JSON ARRAY THEN false
            ELSE json_array_length(authors::json) > 0 END)
        CHECK (CASE WHEN authors IS JSON ARRAY THEN json_array_length(authors::json) <= 1000 END),
    submitted_at utc_date,
    revised_at   utc_date,
    CHECK ((item_id IS NULL) = (title IS NULL)
        AND (item_id IS NULL) = (summary IS NULL)
        AND (item_id IS NULL) = (authors IS NULL)
        AND (item_id IS NULL) = (submitted_at IS NULL)
        AND (item_id IS NULL) = (revised_at IS NULL))
);

CREATE TABLE highlight (
    highlight_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zotero_key       text NOT NULL UNIQUE CHECK (zotero_key ~ '^[0-9A-Z]{8}$'),
    text             text CHECK (length(text) <= 10000),
    comment          text CHECK (length(comment) <= 10000),
    highlighted_at   utc_date NOT NULL,
    revised_at       utc_date,
    withdrawn_at     utc_date,
    item_id          bigint NOT NULL REFERENCES item (id) ON DELETE CASCADE,
    CHECK (text IS NOT NULL OR comment IS NOT NULL)
);

CREATE INDEX highlight_item_id ON highlight (item_id);

CREATE TABLE trend (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_data_id     bigint NOT NULL REFERENCES raw_data (id),
    window_end      utc_day NOT NULL,
    repository_id   bigint NOT NULL CHECK (repository_id > 0),
    repository_name text NOT NULL
        CHECK (repository_name ~ '^.+/.+$')
        CHECK (length(repository_name) <= 255),
    stars_gained    bigint NOT NULL CHECK (stars_gained >= 0),
    forks_gained    bigint NOT NULL CHECK (forks_gained >= 0),
    UNIQUE (window_end, repository_id)
);

CREATE INDEX trend_raw_data_id ON trend (raw_data_id);

CREATE TABLE vulnerability (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cve_id         text NOT NULL UNIQUE
        CHECK (cve_id ~ '^CVE-[0-9]{4}-[0-9]{4}')
        CHECK (length(cve_id) <= 20),
    item_id        bigint UNIQUE REFERENCES item (id),
    name           text CHECK (length(name) <= 500),
    description    text CHECK (length(description) <= 5000),
    vendor         text CHECK (length(vendor) <= 200),
    product        text CHECK (length(product) <= 500),
    date_added     utc_date,
    ransomware_use text CHECK (ransomware_use IN ('Known', 'Unknown')),
    revised_at     utc_date,
    withdrawn_at   utc_date,
    CHECK ((item_id IS NULL) = (name IS NULL)
        AND (item_id IS NULL) = (description IS NULL)
        AND (item_id IS NULL) = (vendor IS NULL)
        AND (item_id IS NULL) = (product IS NULL)
        AND (item_id IS NULL) = (date_added IS NULL)
        AND (item_id IS NULL) = (ransomware_use IS NULL)
        AND (item_id IS NOT NULL OR (revised_at IS NULL AND withdrawn_at IS NULL)))
);

-- citext: GitHub ignores the case of a repository name, as COLLATE NOCASE does in schema.sql.
CREATE TABLE tracked_repository (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_name citext NOT NULL UNIQUE CHECK (repository_name ~ '^.+/.+$'),
    ecosystem       text NOT NULL CHECK (ecosystem IN ('pip', 'npm')),
    packages        text NOT NULL
        CHECK (CASE WHEN packages IS NOT JSON ARRAY THEN false
            ELSE json_array_length(packages::json) > 0 END)
);

CREATE TABLE release (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id               bigint NOT NULL UNIQUE,
    kind                  text NOT NULL CHECK (kind = 'release'),
    tracked_repository_id bigint NOT NULL REFERENCES tracked_repository (id),
    release_id            bigint NOT NULL UNIQUE,
    tag_name              text NOT NULL
        CHECK (length(tag_name) > 0)
        CHECK (length(tag_name) <= 255),
    name                  text CHECK (length(name) <= 255),
    body                  text CHECK (length(body) <= 125000),
    published_at          utc_date NOT NULL,
    url                   text NOT NULL
        CHECK (url ~ '^https://')
        CHECK (length(url) <= 2000),
    FOREIGN KEY (item_id, kind) REFERENCES item (id, kind)
);

CREATE INDEX release_tracked_repository_id ON release (tracked_repository_id);

CREATE TABLE advisory (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id          bigint NOT NULL UNIQUE,
    kind             text NOT NULL CHECK (kind = 'advisory'),
    ghsa_id          text NOT NULL UNIQUE
        CHECK (ghsa_id ~ '^GHSA-')
        CHECK (length(ghsa_id) <= 19),
    vulnerability_id bigint REFERENCES vulnerability (id),
    summary          text NOT NULL CHECK (length(summary) <= 1024),
    published_at     utc_date NOT NULL,
    url              text NOT NULL
        CHECK (url ~ '^https://')
        CHECK (length(url) <= 2000),
    packages         text NOT NULL
        CHECK (CASE WHEN packages IS NOT JSON ARRAY THEN false
            ELSE json_array_length(packages::json) > 0 END)
        CHECK (CASE WHEN packages IS JSON ARRAY THEN json_array_length(packages::json) <= 100 END),
    FOREIGN KEY (item_id, kind) REFERENCES item (id, kind)
);

CREATE INDEX advisory_vulnerability_id ON advisory (vulnerability_id);

CREATE TABLE newsletter_article (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id        bigint NOT NULL UNIQUE,
    kind           text NOT NULL CHECK (kind = 'newsletter_article'),
    -- Lowercase letters without accent, as the GLOB of schema.sql: [a-z] is ASCII in the
    -- collation C.
    edition        text NOT NULL
        CHECK (edition ~ '^[a-z]+$')
        CHECK (length(edition) <= 20),
    edition_date   utc_date NOT NULL,
    rank           bigint NOT NULL CHECK (rank >= 1),
    title          text NOT NULL CHECK (length(title) <= 500),
    summary        text NOT NULL CHECK (length(summary) <= 5000),
    url            text NOT NULL
        CHECK (url ~ '^https://')
        CHECK (length(url) <= 2000),
    publication_id bigint REFERENCES publication (id),
    UNIQUE (edition, edition_date, rank),
    FOREIGN KEY (item_id, kind) REFERENCES item (id, kind)
);

CREATE INDEX newsletter_article_publication_id ON newsletter_article (publication_id);

CREATE TABLE zotero_entry (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id        bigint NOT NULL UNIQUE,
    kind           text NOT NULL CHECK (kind = 'zotero_entry'),
    zotero_key     text NOT NULL UNIQUE CHECK (zotero_key ~ '^[0-9A-Z]{8}$'),
    item_type      text NOT NULL CHECK (length(item_type) <= 100),
    title          text NOT NULL CHECK (length(title) <= 1000),
    url            text
        CHECK (url ~ '^https?://')
        CHECK (length(url) <= 2000),
    saved_at       utc_date NOT NULL,
    publication_id bigint REFERENCES publication (id),
    revised_at     utc_date,
    withdrawn_at   utc_date,
    FOREIGN KEY (item_id, kind) REFERENCES item (id, kind)
);

CREATE INDEX zotero_entry_publication_id ON zotero_entry (publication_id);

-- The CHECK of the dates of clip are those of schema.sql, already portable. Its URL is unique by
-- its md5: an entry of a B-tree index holds about 2,700 bytes, and 2,000 characters of UTF-8 can
-- take 8,000 (docs/stockage.md).
CREATE TABLE clip (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id      bigint NOT NULL UNIQUE,
    kind         text NOT NULL CHECK (kind = 'clip'),
    url          text NOT NULL
        CHECK (substr(url, 1, 8) = 'https://' OR substr(url, 1, 7) = 'http://')
        CHECK (length(url) <= 2000),
    title        text NOT NULL
        CHECK (length(title) > 0)
        CHECK (length(title) <= 1000),
    body         text NOT NULL CHECK (length(body) <= 1000000),
    saved_at     text NOT NULL
        CHECK (length(saved_at) = 20 AND substr(saved_at, 11, 1) = 'T'
            AND substr(saved_at, 20, 1) = 'Z'),
    published_at text
        CHECK (length(published_at) = 20 AND substr(published_at, 11, 1) = 'T'
            AND substr(published_at, 20, 1) = 'Z'),
    revised_at   text
        CHECK (length(revised_at) = 20 AND substr(revised_at, 11, 1) = 'T'
            AND substr(revised_at, 20, 1) = 'Z'),
    FOREIGN KEY (item_id, kind) REFERENCES item (id, kind)
);

CREATE UNIQUE INDEX clip_url_md5 ON clip (md5(url));

CREATE TABLE tag (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
        CHECK (length(name) > 0)
        CHECK (length(name) <= 100)
);

CREATE TABLE item_has_tag (
    item_id bigint NOT NULL REFERENCES item (id) ON DELETE CASCADE,
    tag_id  bigint NOT NULL REFERENCES tag (id),
    PRIMARY KEY (item_id, tag_id)
);

CREATE INDEX item_has_tag_tag_id ON item_has_tag (tag_id);
